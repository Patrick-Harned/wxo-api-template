  lazy val makePixTransfer: ServerEndpoint[Any, IO] =
    OIDCAuthMiddleware.authenticatedEndpoint.post
      .in("api" / "pix" / "transfer")
      .in(jsonBody[PixTransferRequest])
      .out(jsonBody[List[Persisted[transactions]]])
      .description(
        "Send money instantly to another user using their PIX key. " +
          "The money will be deducted from your balance and added to the recipient. " +
          "Example: {\"receiver_pix_key\": \"maria@email.com\", \"amount\": 50.00, \"description\": \"Lunch payment\"}"
      )
      .serverLogic { user => request =>
        // 1. Get sender info
        val senderQuery = {
          val empty = summon[EmptyOptional[users]].empty
          empty.copy[OptionalField](name = Some(user.userInfo.sub))
        }

        val senderResult: IO[Either[ApiError, List[Persisted[users]]]] = transform(
          db.withConnection(
            _.queryParameterized[Optional[users], Persisted[users]](senderQuery)
          )
        )

        senderResult.flatMap {
          case Left(error) => IO.pure(Left(error))
          case Right(senders) =>
            senders.headOption match {
              case None =>
                IO.pure(Left(ApiError("Sender account not found. Please open an account first.")))
              case Some(sender) =>
                // 2. Validate balance
                if (sender.balance < request.amount) {
                  IO.pure(
                    Left(
                      ApiError(
                        s"Insufficient balance. Available: R$$${sender.balance}, Required: R$$${request.amount}"
                      )
                    )
                  )
                }
                else {
                  // 3. Lookup receiver by PIX key
                  val keyQuery = {
                    val empty = summon[EmptyOptional[pix_keys]].empty
                    empty.copy[OptionalField](
                      key_value = Some(request.receiver_pix_key),
                      status = Some("active")
                    )
                  }

                  val keyResult: IO[Either[ApiError, List[Persisted[pix_keys]]]] = transform(
                    db.withConnection(
                      _.queryParameterized[Optional[pix_keys], Persisted[pix_keys]](keyQuery)
                    )
                  )

                  keyResult.flatMap {
                    case Left(error) => IO.pure(Left(error))
                    case Right(keys) =>
                      keys.headOption match {
                        case None =>
                          IO.pure(
                            Left(
                              ApiError(s"Receiver PIX key not found: ${request.receiver_pix_key}")
                            )
                          )
                        case Some(pixKey) =>
                          // 4. Get receiver info
                          val receiverQuery = {
                            val empty = summon[EmptyOptional[users]].empty
                            empty.copy[OptionalField](user_id = Some(pixKey.user_id))
                          }

                          val receiverResult
                              : IO[Either[ApiError, List[Persisted[users]]]] = transform(
                            db.withConnection(
                              _.queryParameterized[Optional[users], Persisted[users]](receiverQuery)
                            )
                          )

                          receiverResult.flatMap {
                            case Left(error) => IO.pure(Left(error))
                            case Right(receivers) =>
                              receivers.headOption match {
                                case None => IO.pure(Left(ApiError("Receiver account not found")))
                                case Some(receiver) =>
                                  // 5. Update balances and create transaction in same connection
                                  val transactionUuid = java.util.UUID.randomUUID().toString

                                  val result =
                                    db.withConnection { conn =>
                                      // Update sender balance
                                      val updatedSender = sender.copy[PersistedField](
                                        balance = sender.balance - request.amount
                                      )
                                      conn.update[Persisted[users], Persisted[users]](
                                        updatedSender
                                      )

                                      // Update receiver balance
                                      val updatedReceiver = receiver.copy[PersistedField](
                                        balance = receiver.balance + request.amount
                                      )
                                      conn.update[Persisted[users], Persisted[users]](
                                        updatedReceiver
                                      )

                                      // Create transaction record
                                      val newTransaction: New[transactions] = transactions(
                                        None,
                                        transactionUuid,
                                        sender.user_id.value,
                                        receiver.user_id.value,
                                        request.amount,
                                        "pix_key",
                                        Some(request.receiver_pix_key),
                                        request.description.getOrElse(""),
                                        Some("completed"),
                                        None,
                                        None
                                      )

                                      conn.insert[New[transactions], Persisted[transactions]](
                                        newTransaction
                                      )
                                    }

                                  transform(result)
                              }
                          }
                      }
                  }
                }
            }
        }
      }

