                    sender_user_id = Some(foundUser.user_id.value)
                  )
                }

                transform(
                  db.withConnection(
                    _.queryParameterized[Optional[transactions], Persisted[transactions]](
                      txnQuery,
                      limit,
                      offset
                    )
                  )
                )
            }
        }
      }

