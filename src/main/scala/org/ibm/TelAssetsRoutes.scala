  implicit def transformJsonString[T[_[_]] <: Product](
      fut: Future[Try[Iterator[JsonString[Persisted[T]]]]]
  ): IO[Either[ApiError, List[JsonString[Persisted[T]]]]] =
    IO.fromFuture(IO.blocking(fut)).map {
      case scala.util.Success(iter) => Right(iter.toList)
      case scala.util.Failure(ex)   => Left(ApiError(ex.getMessage))
    }

  implicit def transform[T[_[_]]](
      fut: Future[Try[Iterator[Persisted[T]]]]
  ): IO[Either[ApiError, List[Persisted[T]]]] =
    IO.fromFuture(IO.blocking(fut)).map {
      case scala.util.Success(iter) => Right(iter.toList)
      case scala.util.Failure(ex)   => Left(ApiError(ex.getMessage))
    }
  implicit def transformString[T[_[_]]](
      fut: Future[Try[Iterator[String]]]
  ): IO[Either[ApiError, String]] =
    IO.fromFuture(IO.blocking(fut)).map {
      case scala.util.Success(iter) => Right(iter.mkString("[", ",", "]"))
      case scala.util.Failure(ex)   => Left(ApiError(ex.getMessage))
    }

  def endpointForNoInput[T[_[_]] <: Product](
      endpointName: String
  )(using
      db: Database,
      jd: JsonDeserializer[Persisted[T]],
      js: JsonSerializer[Persisted[T]],
      sqls: SqlSelect[Persisted[T]],
      sqlsO: SqlSelect[Optional[T]],
      row: Row[Persisted[T]],
      mapDeser: MapDeserializer[Optional[T]],
      fb: FieldBinder[Optional[T]],
      schema: Schema[Persisted[T]]
  ): ServerEndpoint[Any, IO] = {

    type P = Persisted[T] // T[PersistedField]
    type O = Optional[T]  // T[OptionalField]

    OIDCAuthMiddleware.authenticatedEndpoint.get
      .in("api" / endpointName)
      .in(
        sttp.tapir
          .query[Option[Int]]("limit")
          .description(
            "Limits the result set to N records. Defaults to 10. Use this combined with offset to paginate results."
          )
      )
      .in(
        sttp.tapir
          .query[Option[Int]]("offset")
          .description(
            "Offsets the result set by N records. Defaults to 0. Use this combined with limit to paginate results"
          )
      )
      .out(jsonBody[List[P]])
      .description(endpointName)
      .serverLogic { user => (limit, offset) =>
        transform(
          db.withConnection(
            _.query[P](limit.orElse(Some(10)), offset.orElse(Some(0)))
          )
        )
      }
  }

  def endpointForPost[T[_[_]] <: Product](
      endpointName: String,
      description: Option[String] = None
  )(using
      db: Database,
      jd: JsonDeserializer[New[T]],
      jdp: JsonDeserializer[Persisted[T]],
      ib: InsertBinder[New[T]],
      si: SqlInsert[New[T]],
      js: JsonSerializer[Persisted[T]],
      sqls: SqlSelect[Persisted[T]],
      sqlsO: SqlSelect[Optional[T]],
      row: Row[Persisted[T]],
      mapDeser: MapDeserializer[Optional[T]],
      fb: FieldBinder[Optional[T]],
      schema: Schema[New[T]],
      schemap: Schema[Persisted[T]],
      ep: EndpointInput[Optional[T]]
  ): ServerEndpoint[Any, IO] = {

    type N = New[T]       // T[PersistedField]
    type P = Persisted[T] // T[OptionalField]

    val base = OIDCAuthMiddleware.authenticatedEndpoint.post
      .in(jsonBody[New[T]])
      .in("api" / endpointName)
      .out(jsonBody[List[P]])
      .description(endpointName)
      .serverLogic { user => params =>
        transform(
          db.withConnection {
            _.insert[N, P](params)
          }
        )
      }
    description match
      case Some(value) => base.description(value)
      case _           => base

  }

  def endpointFor[T[_[_]] <: Product](
      endpointName: String,
      description: Option[String] = None
  )(using
      db: Database,
      jd: JsonDeserializer[Persisted[T]],
      js: JsonSerializer[Persisted[T]],
      sqls: SqlSelect[Persisted[T]],
      sqlsO: SqlSelect[Optional[T]],
      row: Row[Persisted[T]],
      mapDeser: MapDeserializer[Optional[T]],
      fb: FieldBinder[Optional[T]],
      schema: Schema[Persisted[T]],
      ep: EndpointInput[Optional[T]]
  ): ServerEndpoint[Any, IO] = {

    type P = Persisted[T] // T[PersistedField]
    type O = Optional[T]  // T[OptionalField]

    val base = OIDCAuthMiddleware.authenticatedEndpoint.get
      .in("api" / endpointName)
      .in(ep)
      .in(
        sttp.tapir
          .query[Option[Int]]("limit")
          .description(
            "Limits the result set to N records. Defaults to 10. Use this combined with offset to paginate results."
          )
      )
      .in(
        sttp.tapir
          .query[Option[Int]]("offset")
          .description(
            "Offsets the result set by N records. Defaults to 0. Use this combined with limit to paginate results"
          )
      )
      .out(jsonBody[List[P]])
      .description(endpointName)
      .serverLogic { user => (params, limit, offset) =>
        if params.productIterator.forall(_ == None) then
          transform(
            db.withConnection(
              _.query[P](limit.orElse(Some(10)), offset.orElse(Some(0)))
            )
          )
        else

          transform(
            db.withConnection {
              _.queryParameterized[O, P](params, limit, offset)
            }
          )
      }
    description match
      case Some(value) => base.description(value)
      case _           => base

  }
